import { writeFileSync } from "node:fs";
import { staticBlogPosts } from "../src/data/staticBlogPosts";
import { DISPENSARY_MENUS } from "../src/data/dispensaryMenus";
import { articleKnowledge, lefStrainKnowledge } from "../src/lib/ragContent";

const menu = DISPENSARY_MENUS.find(m => m.id === "leaf-labs");
if (!menu) throw new Error("LëF Labs catalogue missing");
const posts = staticBlogPosts.filter(p => p.published_at >= "2026-08-07" && Date.parse(p.published_at) <= Date.now());
const docs = [...posts.flatMap(articleKnowledge), ...lefStrainKnowledge(menu.items)];
writeFileSync("supabase/functions/_shared/content-refresh-corpus.ts", `// Generated by scripts/prepare-rag-refresh.ts from public article and catalogue sources.\nexport const CONTENT_REFRESH_CORPUS = ${JSON.stringify(docs, null, 2)};\n`);
console.log(JSON.stringify({ articles: posts.length, passages: docs.filter(d => d.category === "blog").length, strains: docs.filter(d => d.category === "strain").length }));