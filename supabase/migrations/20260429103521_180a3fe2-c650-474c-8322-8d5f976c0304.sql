## 🚬 Smoking & Vaping: The Express Lane

When you inhale cannabis, **THC enters your bloodstream through the lungs almost instantly**.

- **Onset:** seconds to a few minutes
- **Peak:** 15–30 minutes
- **Duration:** roughly 1–3 hours
- **Bioavailability:** ~20–30% of THC actually reaches your bloodstream

Because it skips the digestive system, the THC molecule that hits your brain is *delta-9-THC* — the classic, familiar high. It's predictable, easy to titrate (you can take one puff, wait, take another), and fades relatively quickly.

## 🍪 Edibles: The Scenic Route Through Your Liver

Edibles take a completely different journey. After you eat them:

1. THC travels through your **stomach and small intestine**.
2. It's absorbed into the bloodstream and routed straight to the **liver**.
3. The liver converts delta-9-THC into **11-hydroxy-THC** — a metabolite that is significantly **more potent** and crosses the blood-brain barrier more efficiently.

That's why edibles feel like a *different* high, not just a stronger one.

- **Onset:** 30 minutes to 2 hours (sometimes longer on a full stomach)
- **Peak:** 2–4 hours in
- **Duration:** 4–8+ hours
- **Bioavailability:** lower (~4–20%) but the metabolite is stronger

## ⚠️ Why People Get Caught Out

The most common edible mistake is the same one almost everyone makes once:

> "I don't feel anything yet… I'll just have another."

Forty-five minutes later, both doses kick in *together*, and you're in for a much longer ride than you planned.

**Cuddles' golden rule:** *Start low, go slow.* Try 2.5–5 mg of THC, wait at least **2 hours**, and only then consider redosing.

